#!/usr/bin/env bash

ensure_runtime_config_imports() {
    local application_config=$1
    shift
    local import_path additional_imports=

    if [[ ! -f "$application_config" ]]; then
        printf '%s\n' "Run 'make setup' or 'make install' before configuring runtime settings." >&2
        return 1
    fi

    for import_path in "$@"; do
        if ! awk -v wanted="$import_path" '
            /^spring:[[:space:]]*(#.*)?$/ { in_spring = 1; next }
            in_spring && /^[^[:space:]#]/ { in_spring = 0 }
            in_spring && /^  config:[[:space:]]*(#.*)?$/ { in_config = 1; next }
            in_spring && in_config && /^  [^[:space:]#]/ { in_config = 0 }
            in_spring && in_config && /^    import:[[:space:]]*optional:file:/ {
                value = substr($0, index($0, ":") + 1)
                sub(/^[[:space:]]+/, "", value)
                count = split(value, imports, ",")
                for (i = 1; i <= count; i++) {
                    if (imports[i] == wanted) {
                        found = 1
                    }
                }
            }
            END { exit !found }
        ' "$application_config"; then
            if [[ -n "$additional_imports" ]]; then
                additional_imports+=,
            fi
            additional_imports+="$import_path"
        fi
    done
    [[ -n "$additional_imports" ]] || return 0

    if ! awk '
        /^spring:[[:space:]]*(#.*)?$/ { in_spring = 1; next }
        in_spring && /^[^[:space:]#]/ { in_spring = 0 }
        in_spring && /^  config:[[:space:]]*(#.*)?$/ { in_config = 1; next }
        in_spring && in_config && /^  [^[:space:]#]/ { in_config = 0 }
        in_spring && in_config && /^    import:[[:space:]]*optional:file:/ { found = 1 }
        END { exit !found }
    ' "$application_config"; then
        printf '%s\n' \
            "Cannot safely add runtime configuration imports to $application_config." \
            "Use the scalar 'spring.config.import' format generated by 'make setup'." >&2
        return 1
    fi

    local temp_file
    temp_file="$(mktemp "${application_config}.XXXXXX")"
    if ! awk -v additions="$additional_imports" '
        function append_imports(value, additions, count, paths, existing, existing_count, i, j, found) {
            count = split(additions, paths, ",")
            for (i = 1; i <= count; i++) {
                existing_count = split(value, existing, ",")
                found = 0
                for (j = 1; j <= existing_count; j++) {
                    if (existing[j] == paths[i]) {
                        found = 1
                    }
                }
                if (!found) {
                    value = value (value == "" ? "" : ",") paths[i]
                }
            }
            return value
        }
        /^spring:[[:space:]]*(#.*)?$/ { in_spring = 1; next }
        in_spring && /^[^[:space:]#]/ { in_spring = 0 }
        in_spring && /^  config:[[:space:]]*(#.*)?$/ { in_config = 1; next }
        in_spring && in_config && /^  [^[:space:]#]/ { in_config = 0 }
        in_spring && in_config && /^    import:[[:space:]]*/ {
            value = substr($0, index($0, ":") + 1)
            sub(/^[[:space:]]+/, "", value)
            print "    import: " append_imports(value, additions)
            next
        }
        { print }
    ' "$application_config" > "$temp_file"; then
        rm -f "$temp_file"
        return 1
    fi
    chmod 600 "$temp_file"
    mv "$temp_file" "$application_config"
}

read_setup_value() {
    local prompt=$1 default_value=$2 value
    read -r -p "$prompt [$default_value]: " value
    printf '%s' "${value:-$default_value}"
}

read_setup_yes_no() {
    local prompt=$1 default_value=$2 value
    read -r -p "$prompt [$default_value]: " value
    value=${value:-$default_value}
    case "$value" in
        y|Y|yes|YES|Yes) printf 'true' ;;
        n|N|no|NO|No) printf 'false' ;;
        *)
            printf '%s\n' "Enter yes or no." >&2
            return 1
            ;;
    esac
}

read_setup_secret() {
    local prompt=$1 value
    read -r -s -p "$prompt: " value
    printf '\n' >&2
    printf '%s' "$value"
}

yaml_quote() {
    printf "'%s'" "$(printf '%s' "$1" | sed "s/'/''/g")"
}

validate_setup_file_path() {
    local label=$1 path=$2
    [[ -f "$path" && -r "$path" && "$path" != *[[:space:]]* ]] || {
        printf '%s must be an existing, readable file path without whitespace: %s\n' \
            "$label" "$path" >&2
        return 1
    }
    if [[ "$path" != /* ]]; then
        path="$PWD/$path"
    fi
    printf '%s' "$path"
}
